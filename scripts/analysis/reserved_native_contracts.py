"""Bind forty baseline reserved entries to complete, exact-PE function bytes.

No original/native code, test fixture, compiler or game is executed. Registered
table provenance and the entire pointer-run hash are checked before selecting
entries. JavaScript974..976/1006 are deliberately not in this reserved family.
"""
from __future__ import annotations

import json
import struct

from recovery_A_20261116 import ROOT, Image, sha
from recovery_A_native_profile_20261116 import exact_stub

SLOTS = (429, 439, 543, 544, 545, 546, 547, 548, 550, 551, 552, 553, 554, 555,
         556, 559, 560, 561, 562, 563, 573, 575, 578, 579, 580, 581, 626, 627,
         642, 643, 644, 652, 660, 661, 670, 671, 672, 673, 686, 687)


def main() -> None:
    evidence = json.loads((ROOT / "reports/recovery_A_20261116_feature_profiles.json").read_text(encoding="utf-8"))
    profiles = []
    for profile in evidence["profiles"]:
        image = Image(ROOT / profile["binary_paths"][0], profile["sha256"])
        table = profile["table_fingerprint"]
        count = table["identified_pointer_count"]
        entries = [image.u32(table["table_rva"] + n * 4) for n in range(count)]
        if any(value is None for value in entries) or sha(b"".join(
            struct.pack("<I", value - image.base) for value in entries
        )) != table["entry_rvas_sha256"] or not profile["registration_evidence"]:
            raise ValueError("registered ordinary table identity changed")
        rows = []
        for slot in SLOTS:
            if slot >= count:
                raise ValueError("reserved slot exceeds registered pointer run")
            rva = entries[slot] - image.base
            proof = exact_stub(image, rva)
            if proof is None:
                raise ValueError(f"native{slot} has real behavior in {profile['binary_paths'][0]}")
            rows.append({"index": slot, "entry_rva": rva, "constant": proof})
        profiles.append({"sha256": image.digest, "paths": profile["binary_paths"],
                         "table_fingerprint": table, "slots": rows})
    report = {"schema": "cs2-reserved-native-contracts/v1", "profiles": profiles,
              "indices": SLOTS, "profile_count": len(profiles),
              "exact_slot_bindings": sum(len(p["slots"]) for p in profiles),
              "original_code_executed": False, "compiler_invoked": False,
              "scope": "complete local constant functions only, not full engine or game equivalence"}
    (ROOT / "reports/reserved_native_contracts_20261117.json").write_text(
        json.dumps(report, indent=2) + "\n", encoding="utf-8")
    lines = ["//! Exact-PE reserved ordinary functions; complete mov/ret byte proofs only.",
             "//! Generated by scripts/analysis/reserved_native_contracts.py; no copied engine code.",
             "use cs2_script::{NativeReturn, Result, ScriptError};", "",
             "pub(super) fn call(sha256: &str, index: u32) -> Result<NativeReturn> {",
             "    let result = match sha256 {"]
    for profile in profiles:
        groups = {}
        for row in profile["slots"]:
            constant = row["constant"]
            key = (constant["callback_status"], constant["output_dword"])
            groups.setdefault(key, []).append(row["index"])
        lines.append('        "' + profile["sha256"] + '" => match index {')
        for (status, value), slots in groups.items():
            outcome = "NativeReturn::Continue" if status == 2 else f"NativeReturn::Value({value})"
            lines.append("            " + " | ".join(map(str, slots)) + " => Some(" + outcome + "),")
        lines += ["            _ => None,", "        },"]
    lines += ["        _ => None,", "    };",
              "    result.ok_or(ScriptError::UnimplementedNativeCall { index })", "}", ""]
    (ROOT / "simulator/crates/desktop/src/reserved_native.rs").write_text("\n".join(lines), encoding="utf-8")
    print(json.dumps({"profiles": len(profiles), "indices": len(SLOTS),
                      "exact_slot_bindings": report["exact_slot_bindings"]}))


if __name__ == "__main__":
    main()
