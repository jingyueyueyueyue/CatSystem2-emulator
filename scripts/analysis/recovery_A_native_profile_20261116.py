def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--summary", type=Path, default=ROOT/"reports/recovery_A_20261116_summary.json")
    parser.add_argument("--native-coverage", type=Path, default=ROOT/"reports/native_coverage_20261116.json")
    parser.add_argument("--provenance", type=Path, default=ROOT/"reports/kcs_call_inventory_20261116.json")
    parser.add_argument("--output-prefix", type=Path, default=ROOT/"reports/recovery_A_20261116_feature_profiles")
    parser.add_argument("--write-rust", action="store_true")
    parser.add_argument("--rust-output", type=Path, default=ROOT/"simulator/crates/runtime/src/native_profile.rs")
    args = parser.parse_args()
    summary, native, provenance = (read_json(p) for p in
                                   [args.summary, args.native_coverage, args.provenance])
    sensitive = {n["index"] for n in native["natives"] if n["status"] == "version-sensitive-constant"}
    usage = collect_usage(provenance)
    by_digest = defaultdict(list)
    for binary in summary["perPE"]:
        if binary["binary_path"].lower().endswith(".exe"):
            by_digest[binary["sha256"]].append(binary)
    profiles, no_profile = [], []
    validation = Counter(validate_stub_classifier())
    for digest, binaries in by_digest.items():
        if not binaries[0]["summary"]["registered_table_entry_count"]:
            no_profile.append({"sha256": digest,
                               "binary_paths": [b["binary_path"] for b in binaries],
                               "status": "ordinary-table-not-previously-identified",
                               "profile": None})
            continue
        binary = binaries[0]
        print("Profiles", binary["binary_path"].encode("ascii", "backslashreplace").decode(), flush=True)
        image = Image(ROOT/binary["binary_path"], digest)
        _, refs = registrations(image)
        tables = [t for t in classify_tables(image, refs) if t["table_hint"] == "ordinary"]
        if len(tables) != 1:
            raise ValueError("Expected one independently rediscovered ordinary table")
        table, selected = tables[0], []
        game_root = root_for_binary(binary, provenance)
        calls = usage.get(str(game_root).casefold(), {}) if game_root else {}
        for index in TARGETS:
            observed = dict(calls.get(index, {}))
            row = {"index": index, "table": "ordinary",
                   "in_current_sensitive_32_snapshot": index in sensitive,
                   "ordinary_local_argument_byte_counts": observed,
                   "baseline_reference": "Value(0)" if index in ZERO_BASELINE else "Continue",
                   "implemented_claim": False}
            if index >= len(table["slots"]):
                row.update(status="outside-identified-pointer-run", entry_rva=None, constant=None)
                selected.append(row)
                continue
            rva = table["slots"][index]["entry_rva"]
            assert image.u32(table["table_rva"]+4*index) == image.base+rva
            validation["table_pointers_checked"] += 1
            constant = exact_stub(image, rva)
            raw = image.get(rva, 64)
            row.update(entry_rva=rva, entry_va=image.base+rva,
                       status="exact-constant-stub" if constant else "nonconstant-requires-implementation",
                       constant=constant, first_64_bytes=raw.hex(),
                       first_64_sha256=sha(raw),
                       disassembly_prefix=[instruction_row(i, image.base) for i in image.insns(rva, 64)])
            if constant:
                validation["complete_stubs_checked"] += 1
                row["behavior_differs_from_baseline"] = constant["output_dword"] not in {None, 0}
            else:
                row["behavior_differs_from_baseline"] = True
            selected.append(row)
        profile = {"sha256": digest, "file_version": image.identity()["file_version"],
                   "binary_paths": [b["binary_path"] for b in binaries],
                   "file_size": len(image.data),
                   "table_fingerprint": binding_hashes(image, table, selected),
                   "registration_evidence": table["registration_sites"],
                   "slots": selected}
        assert profile["file_version"] is not None
        profiles.append(profile)
    profiles.sort(key=lambda p: p["sha256"])
    validation.update(validate_identity_matching(profiles))
    by_status = Counter(r["status"] for p in profiles for r in p["slots"])
    nonconstant = [r for p in profiles for r in p["slots"] if not r["constant"]
                   and r["entry_rva"] is not None]
    assert all(r["status"] != "exact-constant-stub" for r in nonconstant)
    assert all(len(p["slots"]) == len(TARGETS) for p in profiles)
    assert len({p["sha256"] for p in profiles}) == len(profiles)
    source = rust_source(profiles)
    # Independent accounting guards: no runtime row for an outside-run slot;
    # only the whitelist's proven effects can enter a generated constant line.
    assert source.count("    continuation(")+source.count("    value(") == by_status["exact-constant-stub"]
    assert source.count("    needs_implementation(") == by_status["nonconstant-requires-implementation"]
    for p in profiles:
        assert p["sha256"] in source and p["file_version"] in source
    module_hash = sha(source.encode("utf-8"))
    protected = [ROOT/"simulator/crates/runtime/src/lib.rs", ROOT/"README.md"]
    protected_before = {str(p): sha(p.read_bytes()) for p in protected}
    if args.write_rust:
        output = args.rust_output
        if output.exists() and not output.read_text(encoding="utf-8").startswith(GENERATOR_MARKER):
            raise ValueError("Preserving an existing non-generated native_profile.rs")
        prior_report = args.output_prefix.with_suffix(".json")
        if output.exists() and prior_report.exists():
            prior_hash = read_json(prior_report)["runtime_module"]["sha256"]
            # The initial Windows write may use CRLF. Normalize line endings
            # for the generated-text guard; content changes still fail closed.
            if sha(output.read_text(encoding="utf-8").encode("utf-8")) != prior_hash:
                raise ValueError("Preserving concurrent/human edits to generated native_profile.rs")
        output.write_text(source, encoding="utf-8", newline="\n")
    payload = {
        "schema": "cs2-recovery-A-feature-profiles/v1",
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "status": "exact-constant-stubs-with-SHA-bound-profiles",
        "targets": list(TARGETS), "current_sensitive_source_snapshot_indices": sorted(sensitive),
        "input_sha256": {str(p.relative_to(ROOT)): sha(p.read_bytes()) for p in
                         [args.summary, args.native_coverage, args.provenance]},
        "summary": {"PE_profiles": len(profiles),
                    "PE_paths": sum(len(p["binary_paths"]) for p in profiles),
                    "constant_slot_bindings": by_status["exact-constant-stub"],
                    "nonconstant_slot_bindings": by_status["nonconstant-requires-implementation"],
                    "outside_pointer_run_slot_bindings": by_status["outside-identified-pointer-run"],
                    "PE_images_without_profile": len(no_profile),
                    "sensitive_numeric_slots_in_snapshot": len(sensitive),
                    "sensitive_exact_constant_bindings": sum(
                        r["in_current_sensitive_32_snapshot"] and bool(r["constant"])
                        for p in profiles for r in p["slots"]),
                    "sensitive_nonconstant_bindings": sum(
                        r["in_current_sensitive_32_snapshot"]
                        and r["status"] == "nonconstant-requires-implementation"
                        for p in profiles for r in p["slots"]),
                    "called_constant_bindings": sum(
                        bool(r["ordinary_local_argument_byte_counts"]) and bool(r["constant"])
                        for p in profiles for r in p["slots"]),
                    "called_constant_static_sites": sum(
                        sum(r["ordinary_local_argument_byte_counts"].values())
                        for p in profiles for r in p["slots"] if r["constant"]),
                    "unknown_identity_returns": None,
                    "semantically_implemented_functions_claimed": 0},
        "profiles": profiles, "without_profile": no_profile,
        "validation": dict(validation),
        "runtime_module": {"path": str(args.rust_output.relative_to(ROOT)),
                           "sha256": module_hash, "written": args.write_rust,
                           "actual_file_sha256": (sha(args.rust_output.read_bytes())
                                                  if args.rust_output.exists() else None),
                           "existing_matches_generated_text": (
                               args.rust_output.read_text(encoding="utf-8") == source
                               if args.rust_output.exists() else False),
                           "dependencies": ["cs2_script::NativeReturn"],
                           "lib_and_dispatch_integration": "left-to-parent"},
        "limitations": ["Only complete templates bind constants; conditional globals and status-only suffixes rejected.",
                        "No selection by minimum version or version-only identity.",
                        "Table-pointer length is a proven contiguous run, not the VM bounds check.",
                        "Portable source routes and behavioral completion are separate from profile evidence."]}
    args.output_prefix.with_suffix(".json").write_text(json.dumps(payload, ensure_ascii=False, indent=2)+"\n",
                                                      encoding="utf-8")
    args.output_prefix.with_suffix(".md").write_text(markdown(payload), encoding="utf-8")
    per_pe = []
    for p in profiles:
        per_pe.append({"sha256": p["sha256"], "file_version": p["file_version"],
                       "binary_paths": p["binary_paths"],
                       "table_rva": p["table_fingerprint"]["table_rva"],
                       "constants": [{"index": r["index"], "entry_rva": r["entry_rva"],
                                      "native_status": r["constant"]["callback_status"],
                                      "output_dword": r["constant"]["output_dword"],
                                      "arguments_ignored": True}
                                     for r in p["slots"] if r["constant"]],
                       "requires_implementation": [r["index"] for r in p["slots"]
                                                    if r["status"] == "nonconstant-requires-implementation"],
                       "outside_identified_run": [r["index"] for r in p["slots"]
                                                  if r["status"] == "outside-identified-pointer-run"]})
    small = args.output_prefix.with_name(args.output_prefix.name+"_summary").with_suffix(".json")
    small.write_text(json.dumps({"summary": payload["summary"], "perPE": per_pe},
                                ensure_ascii=False, indent=2)+"\n", encoding="utf-8")
    assert protected_before == {str(p): sha(p.read_bytes()) for p in protected}
    print(json.dumps(payload["summary"], indent=2))
    return 0


