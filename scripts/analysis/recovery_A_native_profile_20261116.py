def exact_stub(image, rva):
    """Two complete, branch-free x86 stdcall templates; no prefix heuristics."""
    raw = image.get(rva, 64)
    if raw.startswith(bytes.fromhex("b802000000c21000")):
        proof, value, status = raw[:8], None, 2
    elif (len(raw) >= 18 and raw[:6] == bytes.fromhex("8b442410c700")
          and raw[10:18] == bytes.fromhex("b801000000c21000")):
        proof, value, status = raw[:18], struct.unpack_from("<I", raw, 6)[0], 1
    else:
        return None
    instructions = image.insns(rva, len(proof))
    assert instructions and instructions[-1].mnemonic == "ret"
    assert sum(i.size for i in instructions) == len(proof)
    assert instructions[-1].op_str == "0x10"
    assert all(i.mnemonic in {"mov", "ret"} for i in instructions)
    return {
        "kind": "continue-preserving-result" if status == 2 else "constant-result",
        "callback_status": status, "output_dword": value,
        "script_arguments_ignored": True, "VM_ignored": True, "task_ignored": True,
        "result_slot_written": value is not None, "stdcall_pop_bytes": 16,
        "complete_stub_length": len(proof), "complete_stub_bytes": proof.hex(),
        "complete_stub_sha256": sha(proof),
        "instructions": [instruction_row(i, image.base) for i in instructions],
        "proof": "entire straight-line function through ret16; no calls, jumps, globals or other stores",
    }


def validate_stub_classifier():
    """Discriminating pure-byte checks; no recovered/native code is executed."""
    class Fixture:
        base = 0

        def __init__(self, code):
            self.code = bytes.fromhex(code)
            self.decoder = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
            self.decoder.detail = True

        def get(self, rva, length):
            return self.code[rva:rva+length]

        def insns(self, rva, length):
            return list(self.decoder.disasm(self.get(rva, length), rva))

    accepted = {
        "b802000000c21000": (2, None),
        "8b442410c70000000000b801000000c21000": (1, 0),
        "8b442410c70001000000b801000000c21000": (1, 1),
    }
    for code, expected in accepted.items():
        row = exact_stub(Fixture(code), 0)
        assert (row["callback_status"], row["output_dword"]) == expected
    rejected = [
        "b801000000c21000",  # Status1 with unwritten output is not a value.
        "8b442410c60000000000b801000000c21000",  # byte store, not DWORD
        "8b44240cc70000000000b801000000c21000",  # writes script args
        "8b442410c7400400000000b801000000c21000",  # adjacent output word
        "8b442410c70000000000b801000000c20800",  # wrong cleanup
        "8b442410c70000000000b801000000",  # truncated, no return
        "833d00001000007405b802000000c21000",  # conditional/global path
        "e800000000b802000000c21000",  # call then status2 is not a stub
    ]
    for code in rejected:
        assert exact_stub(Fixture(code), 0) is None, code
    return {"classifier_positive_cases": len(accepted),
            "classifier_rejected_counterexamples": len(rejected)}


def binding_hashes(image, table, selected):
    entries = b"".join(struct.pack("<I", s["entry_rva"]) for s in table["slots"])
    reviewed = bytearray(b"CS2_ORDINARY_FEATURE_PROOFS_V1\0")
    for row in selected:
        index = row["index"]
        if row["status"] == "outside-identified-pointer-run":
            reviewed += struct.pack("<IIH", index, 0xFFFFFFFF, 0)
            continue
        proof = (bytes.fromhex(row["constant"]["complete_stub_bytes"]) if row["constant"]
                 else bytes.fromhex(row["first_64_bytes"]))
        reviewed += struct.pack("<IIH", index, row["entry_rva"], len(proof)) + proof
    registration = bytearray(b"CS2_ORDINARY_REGISTRATION_V1\0")
    for ref in sorted(table["registration_sites"], key=lambda r: r["call_site_rva"]):
        registration += struct.pack("<II", ref["setter_rva"], ref["call_site_rva"])
        registration += SETTER
        for i in ref["instructions"]:
            value = bytes.fromhex(i["bytes"])
            registration += struct.pack("<IH", i["rva"], len(value)) + value
    return {
        "table_rva": table["table_rva"],
        "identified_pointer_count": len(table["slots"]),
        "entry_rvas_sha256": sha(entries),
        "reviewed_function_bytes_sha256": sha(bytes(reviewed)),
        "registration_instructions_sha256": sha(bytes(registration)),
        "encoding": {
            "entry_rvas": "little-endian u32 RVA per identified table pointer, in slot order",
            "reviewed_function_bytes": "ASCII CS2_ORDINARY_FEATURE_PROOFS_V1 + NUL, then each TARGETS slot: LE u32 index, LE u32 entry_RVA, LE u16 proof_length, proof_bytes; outside-run uses RVA=ffffffff,length=0. Constants use full stub; nonconstants use first64 bytes.",
            "registration_instructions": "ASCII CS2_ORDINARY_REGISTRATION_V1 + NUL, then registration sites in ascending call_RVA: LE u32 setter_RVA,LE u32 call_RVA,15-byte SETTER,each decoded registration instruction LE u32 RVA,LE u16 length,bytes",
        },
    }


def collect_usage(provenance):
    by_root = defaultdict(lambda: defaultdict(Counter))
    for game in provenance["games"]:
        root = str(Path(game["root"]).resolve()).casefold()
        for program in game["programs"]:
            if program.get("table_hint") != "ordinary":
                continue
            resource = program["resource"].lower().replace("\\", "/")
            if resource.endswith("inst/inst.kcs"):
                continue
            for call in program["calls"]:
                if call.get("index") in TARGETS:
                    by_root[root][call["index"]][str(call.get("argument_bytes"))] += 1
    return by_root


def root_for_binary(binary, provenance):
    path = (ROOT/binary["binary_path"]).resolve()
    roots = []
    for game in provenance["games"]:
        root = Path(game["root"]).resolve()
        if path.is_relative_to(root):
            roots.append(root)
    return max(roots, key=lambda p: len(p.parts)) if roots else None


RUST_PREAMBLE = r'''//! Read-only ordinary-table feature evidence for exact PE identities.
//!
//! Complete byte-verified stubs are the only constant outcomes in this module.
//! A nonconstant record explicitly requires an implementation; it must never
//! fall through to a baseline constant. Unreviewed slots also return `None`.
//! File-version text is a consistency check, never a selector on its own.
//! `BinaryFingerprint::digest` is NOT SHA-256 and must not be passed here.
//!
//! This file has no automatic registration or host dispatch. The parent
//! integration must expose this module and bind an independently computed
//! SHA-256 or an independently verified registered ordinary table.

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ConstantNativeReturn {
    /// Native status 2: continue and preserve the script result slot.
    Continue,
    /// Native status 1: write this DWORD and push its four result bytes.
    Value(u32),
}

impl ConstantNativeReturn {
    pub const fn status(self) -> u32 {
        match self {
            Self::Continue => 2,
            Self::Value(_) => 1,
        }
    }

    pub const fn output_dword(self) -> Option<u32> {
        match self {
            Self::Continue => None,
            Self::Value(value) => Some(value),
        }
    }

    pub fn native_return(self) -> cs2_script::NativeReturn {
        match self {
            Self::Continue => cs2_script::NativeReturn::Continue,
            Self::Value(value) => cs2_script::NativeReturn::Value(value),
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum NativeFeatureKind {
    ExactConstant(ConstantNativeReturn),
    /// A callable body exists and fails the strict complete-stub templates.
    /// No complete behavior or unconditional constant is inferred.
    RequiresImplementation,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct NativeFeature {
    pub index: u32,
    pub entry_rva: u32,
    pub kind: NativeFeatureKind,
}

impl NativeFeature {
    pub const fn constant(self) -> Option<ConstantNativeReturn> {
        match self.kind {
            NativeFeatureKind::ExactConstant(value) => Some(value),
            NativeFeatureKind::RequiresImplementation => None,
        }
    }

    /// Only the strict complete stubs prove arguments, VM and task ignored.
    pub const fn ignores_script_arguments(self) -> bool {
        matches!(self.kind, NativeFeatureKind::ExactConstant(_))
    }

    pub const fn proven_stdcall_pop_bytes(self) -> Option<u16> {
        match self.kind {
            NativeFeatureKind::ExactConstant(_) => Some(16),
            NativeFeatureKind::RequiresImplementation => None,
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct OrdinaryTableFingerprint<'a> {
    pub table_rva: u32,
    /// File-backed code-pointer run, not an inferred VM bounds check.
    pub identified_pointer_count: u32,
    pub entry_rvas_sha256: &'a str,
    pub reviewed_function_bytes_sha256: &'a str,
    pub registration_instructions_sha256: &'a str,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct FeatureProfile {
    pub pe_sha256: &'static str,
    pub file_version: &'static str,
    pub table: OrdinaryTableFingerprint<'static>,
    pub reviewed: &'static [NativeFeature],
}

impl FeatureProfile {
    /// None means no verified record; it never authorizes a default constant.
    pub fn feature(&self, index: u32) -> Option<&NativeFeature> {
        self.reviewed
            .binary_search_by_key(&index, |feature| feature.index)
            .ok()
            .map(|position| &self.reviewed[position])
    }

    pub fn constant(&self, index: u32) -> Option<ConstantNativeReturn> {
        self.feature(index).and_then(|feature| feature.constant())
    }
}

const fn continuation(index: u32, entry_rva: u32) -> NativeFeature {
    NativeFeature {
        index,
        entry_rva,
        kind: NativeFeatureKind::ExactConstant(ConstantNativeReturn::Continue),
    }
}

const fn value(index: u32, entry_rva: u32, result: u32) -> NativeFeature {
    NativeFeature {
        index,
        entry_rva,
        kind: NativeFeatureKind::ExactConstant(ConstantNativeReturn::Value(result)),
    }
}

const fn needs_implementation(index: u32, entry_rva: u32) -> NativeFeature {
    NativeFeature {
        index,
        entry_rva,
        kind: NativeFeatureKind::RequiresImplementation,
    }
}

/// Match the actual PE SHA-256. Optional file version must also match exactly.
/// Unknown hashes, malformed values and conflicting versions return None.
/// There is deliberately no version-only or minimum-version constructor.
pub fn profile_for_pe_sha256(
    pe_sha256: &str,
    file_version: Option<&str>,
) -> Option<&'static FeatureProfile> {
    if pe_sha256.len() != 64 || !pe_sha256.bytes().all(|byte| byte.is_ascii_hexdigit()) {
        return None;
    }
    KNOWN_PROFILES.iter().find(|profile| {
        profile.pe_sha256.eq_ignore_ascii_case(pe_sha256)
            && file_version.is_none_or(|version| version == profile.file_version)
    })
}

/// Alternate match after the caller has independently identified an ordinary
/// registered table and hashed its pointer RVAs, inspected code and decoded
/// registration instructions using the report's canonical encoding.
/// Table bytes alone are insufficient: changed target code must fail matching.
pub fn profile_for_registered_table(
    table: OrdinaryTableFingerprint<'_>,
) -> Option<&'static FeatureProfile> {
    KNOWN_PROFILES.iter().find(|profile| {
        let known = profile.table;
        known.table_rva == table.table_rva
            && known.identified_pointer_count == table.identified_pointer_count
            && known.entry_rvas_sha256.eq_ignore_ascii_case(table.entry_rvas_sha256)
            && known
                .reviewed_function_bytes_sha256
                .eq_ignore_ascii_case(table.reviewed_function_bytes_sha256)
            && known
                .registration_instructions_sha256
                .eq_ignore_ascii_case(table.registration_instructions_sha256)
    })
}

pub fn known_profiles() -> &'static [FeatureProfile] {
    KNOWN_PROFILES
}
'''


def rust_source(profiles):
    lines = [GENERATOR_MARKER, "// Evidence: reports/recovery_A_20261116_feature_profiles.json.",
             RUST_PREAMBLE]
    for number, profile in enumerate(profiles):
        lines += [f"// PE SHA-256 {profile['sha256']}; file version {profile['file_version']}.",
                  f"static FEATURES_{number}: &[NativeFeature] = &["]
        for row in profile["slots"]:
            if row["status"] == "outside-identified-pointer-run":
                continue
            n, r = row["index"], row["entry_rva"]
            constant = row["constant"]
            if constant is None:
                expression = f"needs_implementation({n}, 0x{r:08x})"
            elif constant["callback_status"] == 2:
                expression = f"continuation({n}, 0x{r:08x})"
            else:
                expression = f"value({n}, 0x{r:08x}, {constant['output_dword']})"
            lines.append("    " + expression + ",")
        lines += ["];", ""]
    lines += ["static KNOWN_PROFILES: &[FeatureProfile] = &["]
    for number, profile in enumerate(profiles):
        table = profile["table_fingerprint"]
        lines += [
            "    FeatureProfile {",
            f'        pe_sha256: "{profile["sha256"]}",',
            f'        file_version: "{profile["file_version"]}",',
            "        table: OrdinaryTableFingerprint {",
            f'            table_rva: 0x{table["table_rva"]:08x},',
            f'            identified_pointer_count: {table["identified_pointer_count"]},',
            f'            entry_rvas_sha256: "{table["entry_rvas_sha256"]}",',
            f'            reviewed_function_bytes_sha256: "{table["reviewed_function_bytes_sha256"]}",',
            f'            registration_instructions_sha256: "{table["registration_instructions_sha256"]}",',
            "        },",
            f"        reviewed: FEATURES_{number},",
            "    },",
        ]
    lines += ["];", ""]
    return "\n".join(lines)


def validate_identity_matching(profiles):
    """Check table collisions and negative selector cases independently of IO."""
    def by_sha(value, version=None):
        if len(value) != 64 or any(c not in "0123456789abcdefABCDEF" for c in value):
            return None
        return next((p for p in profiles if p["sha256"].lower() == value.lower()
                     and (version is None or version == p["file_version"])), None)

    fields = ("table_rva", "identified_pointer_count", "entry_rvas_sha256",
              "reviewed_function_bytes_sha256", "registration_instructions_sha256")
    bindings = defaultdict(list)
    for p in profiles:
        t = p["table_fingerprint"]
        bindings[tuple(t[f] for f in fields)].append(p)
        assert by_sha(p["sha256"], p["file_version"]) is p
        assert by_sha(p["sha256"].upper()) is p
        assert by_sha(p["sha256"], "unknown-file-version") is None
        changed = dict(t)
        changed["reviewed_function_bytes_sha256"] = "0"*64
        assert not any(all(changed[f] == other["table_fingerprint"][f] for f in fields)
                       for other in profiles)
    assert by_sha("0"*64) is None
    assert by_sha("not-a-sha256") is None
    assert by_sha("g"*64) is None
    # Equal table/code binding may occur in two game PE wrappers, but it must
    # never pick conflicting outcomes. Exact PE identities remain distinct.
    for group in bindings.values():
        def facts(p):
            return [(r["index"], r["entry_rva"], r["status"],
                     (r["constant"]["callback_status"], r["constant"]["output_dword"])
                     if r["constant"] else None) for r in p["slots"]]
        assert all(facts(p) == facts(group[0]) for p in group)
    return {"distinct_table_bindings": len(bindings),
            "SHA_positive_and_conflicting_version_checks": len(profiles)*3,
            "mutated_code_binding_rejections": len(profiles),
            "unknown_identity_rejections": 3}


