"""Extract the hash-pinned Happiness! 2 opening route from the local CST archive."""

import argparse
from hashlib import sha256
from pathlib import Path
from struct import unpack_from

from audit_runtime_evidence import blowfish_le_decrypt, kif_entries
from cst_variants import expand_cst, inspect_body


ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "simulator/crates/desktop/src/happiness_route_data.rs"
SCENES = (
    ("0_01_01", "7fd326a8a41ee87336fa9cb496abb2c16e60822b68ede1afb2fe1d2bb8efadf2", 47, "0_01_02"),
    ("0_01_02", "f2ba499d5e1da7c37cd55ca3e7146e4e559aeb159d4f5514b33efd138328ec29", 52, "0_01_03"),
    ("0_01_03", "2019ca536e996464cb0ff8cb4b2af59e0f514ce9ce6bf56fa4d84e521f452eb8", 62, "0_01_04"),
)


def scene_pages(member, raw, expected_hash, page_count, next_scene):
    if sha256(raw).hexdigest() != expected_hash:
        raise ValueError(f"source changed: {member}")
    body, _ = expand_cst(raw)
    shape = inspect_body(body)
    offsets, strings = shape["offset_table"], shape["string_table"]
    records = []
    for offset in range(16 + offsets, 16 + strings, 4):
        start = 16 + strings + unpack_from("<I", body, offset)[0]
        records.append(body[start:body.index(b"\0", start)])

    pages = []
    for group in range(shape["input_count"]):
        count, start = unpack_from("<II", body, 16 + group * 8)
        numbered = list(enumerate(records[start:start + count], start))
        waits = [index for index, record in numbered if record[1] == 0x02]
        text = [index for index, record in numbered if record[1] == 0x20 and len(record) > 2]
        commands = [record[2:] for _, record in numbered if record[1] == 0x30]
        if any(command.split(maxsplit=1)[0] in {b"fselect", b"select"} for command in commands if command):
            raise ValueError(f"choice needs a separate route entry: {member}/{group}")
        if group == page_count:
            expected = [f"next {next_scene}".encode("ascii")]
            targets = [command for command in commands if command.startswith(b"next ")]
            if waits or text or targets != expected or group + 1 != shape["input_count"]:
                raise ValueError(f"unexpected scene tail: {member}/{group}")
        elif len(waits) != 1 or waits[0] != start + count - 1 or not text:
            raise ValueError(f"unexpected dialogue group: {member}/{group}")
        else:
            pages.append((waits[0], text))
    if len(pages) != page_count:
        raise ValueError(f"unexpected page count: {member}")
    return pages


def generate():
    archive, = (ROOT / "games").glob("Happiness*/scene.int")
    entries, _, cipher = kif_entries(archive, 0xB3738B41)
    by_name = {entry["name"]: entry for entry in entries}
    pages_by_scene = []
    with archive.open("rb") as handle:
        for scene, digest, count, next_scene in SCENES:
            member = f"{scene}.cst"
            entry = by_name[member.encode("ascii")]
            handle.seek(entry["offset"])
            raw = blowfish_le_decrypt(cipher, handle.read(entry["size"]))
            pages_by_scene.append(scene_pages(member, raw, digest, count, next_scene))

    lines = ["//! Generated by scripts/analysis/generate_happiness_opening_route.py.", ""]
    for name, (_, digest, _, _), pages in zip(("FIRST", "SECOND", "THIRD"), SCENES, pages_by_scene):
        lines.extend([
            f'pub(crate) const {name}_SHA256: &str = "{digest}";',
            f"pub(crate) const {name}: &[(i32, &[usize])] = &[",
        ])
        lines.extend(f"    ({wait}, &[{', '.join(map(str, text))}])," for wait, text in pages)
        lines.extend(["];", ""])
    size = sum(map(len, pages_by_scene))
    lines.append(f"pub(crate) const WAITS: [(i32, i32); {size}] = [")
    for pages in pages_by_scene:
        lines.extend(f"    ({group}, {wait})," for group, (wait, _) in enumerate(pages))
    lines.extend(["];", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Compare the generated source without writing it")
    args = parser.parse_args()
    source = generate()
    if args.check:
        if OUTPUT.read_text(encoding="ascii") != source:
            raise SystemExit("Happiness opening route data differs from the source archive")
    else:
        OUTPUT.write_text(source, encoding="ascii", newline="\n")


if __name__ == "__main__":
    main()
