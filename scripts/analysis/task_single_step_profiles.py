"""Recover native1074 only from exact registered PE wrapper/helper bytes.

This decodes immutable images and writes fixed descriptors; it never executes
the original function, the simulator, a compiler, or tests.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import struct

import pefile

ROOT = Path(__file__).resolve().parents[2]
ARCHIVE = ROOT / "archive/2026-11"


def main() -> None:
    ledger = json.loads((ROOT / "reports/recovery_A_20261116.json").read_text(encoding="utf-8"))
    accepted, rejected = [], []
    for digest, record in sorted(ledger["images"].items()):
        tables = [t for t in record["tables"] if t["table_hint"] == "ordinary"
                  and t["registration_chain_verified"] and len(t["slots"]) > 1074]
        if not tables:
            continue
        paths = [b["binary_path"] for b in ledger["binaries"] if b["sha256"] == digest
                 and b["binary_path"].lower().endswith(".exe")]
        if len(tables) != 1 or not paths:
            rejected.append({"sha256": digest, "reason": "no unique registered EXE table"})
            continue
        raw = (ROOT / paths[0]).read_bytes()
        if hashlib.sha256(raw).hexdigest() != digest:
            raise ValueError("PE identity changed")
        pe = pefile.PE(data=raw)
        base = pe.OPTIONAL_HEADER.ImageBase
        table = tables[0]
        entry = table["slots"][1074]["entry_rva"]
        pointer = struct.unpack("<I", pe.get_data(table["table_rva"] + 1074 * 4, 4))[0]
        if pointer != base + entry:
            raise ValueError("registered slot1074 pointer changed")
        code = pe.get_data(entry, 17)
        if code[:5] != bytes.fromhex("8b4c2408e8") or code[9:] != bytes.fromhex("b802000000c21000"):
            rejected.append({"sha256": digest, "entry_rva": entry, "reason": "different wrapper ABI"})
            continue
        helper = entry + 9 + struct.unpack("<i", code[5:9])[0]
        helper_code = pe.get_data(helper, 8)
        if helper_code != bytes.fromhex("c7416401000000c3"):
            rejected.append({"sha256": digest, "entry_rva": entry, "reason": "different receiver field"})
            continue
        # Same base-task update: pause first, otherwise consume64 once and
        # adjust origin58 by now-last60-1. Require the complete local branch.
        update_bytes = bytes.fromhex(
            "837b5c0074118bc5c74364000000002b4360014358eb19"
            "837b640074108bc5c74364000000002b436048014358896b68"
        )
        start = max(0, helper - 0x1000)
        nearby = pe.get_data(start, helper - start)
        offset = nearby.find(update_bytes)
        if offset < 0 or nearby.find(update_bytes, offset + 1) >= 0:
            rejected.append({"sha256": digest, "entry_rva": entry, "reason": "base update not uniquely verified"})
            continue
        accepted.append({"sha256": digest, "path": paths[0], "table_rva": table["table_rva"],
                         "entry_rva": entry, "wrapper_bytes": code.hex(), "helper_rva": helper,
                         "helper_bytes": helper_code.hex(), "update_branch_rva": start + offset,
                         "update_bytes": update_bytes.hex()})
    evidence = {"accepted": accepted, "rejected": rejected, "original_code_executed": False}
    (ARCHIVE / "20261117_C_task_single_step_profiles.json").write_text(
        json.dumps(evidence, indent=2, ensure_ascii=False), encoding="utf-8")
    lines = ["//! Exact-PE native1074 writes the current task's one-step clock flag.",
             "// Generated by scripts/analysis/task_single_step_profiles.py.",
             "pub fn exact_single_step_native(sha256: &str) -> bool {", "    matches!(sha256,"]
    if not accepted:
        raise ValueError("no verified single-step descriptors; source was not changed")
    lines.extend("        " + ("" if n == 0 else "| ") + json.dumps(row["sha256"])
                 for n, row in enumerate(accepted))
    lines += ["    )", "}", ""]
    (ROOT / "simulator/crates/runtime/src/native_task_clock_profile.rs").write_text(
        "\n".join(lines), encoding="utf-8")
    print(json.dumps({"accepted": len(accepted), "rejected": rejected}, indent=2))


if __name__ == "__main__":
    main()
