"""Generate Newton's hash-pinned opening waits from local loose CST files."""

import argparse
from pathlib import Path

from plan_pc_story_08_14_18 import read_scene
from run_playthrough_batch import INVENTORY, ROOT, load_inventory


OUTPUT = ROOT / "simulator/crates/desktop/src/newton_route_data.rs"
SCENES = (
    ("com_001A", "91e7241ee4dc6b0c36d697913cf22bb9649d7ea5b924b88e199a3bcb6e8f4e5b", 57, "com_001B"),
    ("com_001B", "c8d6d9961f410a827df440906dd82c0b2d6a0586450d57dc2db34f9daec7a0e8", 215, "com_001C"),
)


class LooseScenes:
    def __init__(self, game):
        self.members = {path.name.casefold(): path for path in (game / "scene").glob("*.cst")}

    def read(self, scene):
        path = self.members[f"{scene}.cst".casefold()]
        return f"scene/{path.name}", path.read_bytes()


def generate():
    games, _ = load_inventory(INVENTORY)
    reader = LooseScenes(Path(games[16]["root"]))
    lines = ["//! Generated by scripts/analysis/generate_newton_opening_route.py.", ""]
    all_waits = []
    for label, (scene, digest, page_count, successor) in zip(("FIRST", "SECOND"), SCENES):
        data = read_scene(reader, scene)
        pages = data["pages"]
        if (data["sha256"] != digest or len(pages) != page_count
                or [(row["kind"], row["conditional"], row["target"]) for row in data["boundaries"]]
                != [("next", False, successor)]
                or any(page["group"] != group or page["kind"] != "input" or not page["body"]
                       for group, page in enumerate(pages))):
            raise ValueError(f"unexpected source or route in {scene}")
        if label == "SECOND":
            lines.extend([
                f'pub(crate) const SECOND_SHA256: &str = "{digest}";',
                "pub(crate) const SECOND: &[(i32, &[usize])] = &[",
            ])
            lines.extend(f"    ({page['wait']}, &{page['body']})," for page in pages)
            lines.extend(["];", ""])
        all_waits.extend((page["group"], page["wait"]) for page in pages)
    lines.append("pub(crate) const WAITS: &[(i32, i32)] = &[")
    lines.extend(f"    ({group}, {wait})," for group, wait in all_waits)
    lines.extend(["];", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Compare the generated source without writing")
    args = parser.parse_args()
    source = generate()
    if args.check:
        if OUTPUT.read_text(encoding="ascii") != source:
            raise SystemExit("Newton opening data differs from the source CST files")
    else:
        OUTPUT.write_text(source, encoding="ascii", newline="\n")


if __name__ == "__main__":
    main()
