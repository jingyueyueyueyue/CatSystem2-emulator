pub(super) fn returns_vm_identity<'a>(
    slot: &[u8],
    image_base: u32,
    code: impl Fn(u32) -> Option<&'a [u8]>,
    code_sections: impl Iterator<Item = (u32, &'a [u8])>,
) -> bool {
    if !slot.starts_with(UNWRITTEN_RETURN) {
        return false;
    }

    let mut dispatchers = code_sections.flat_map(|(rva, bytes)| {
        bytes.windows(DIRECT_DISPATCH.len()).enumerate().filter_map(move |(offset, prefix)| {
            if !prefix.starts_with(&DIRECT_DISPATCH[..5]) {
                return None;
            }
            let address = rva.checked_add(u32::try_from(offset).ok()?)?;
            Some((address, bytes.get(offset..)?))
        })
    }).filter(|&(rva, bytes)| verified_dispatcher(rva, bytes, image_base, &code).is_some());

    dispatchers.next().is_some() && dispatchers.next().is_none()
}

fn verified_dispatcher<'a>(
    rva: u32,
    body: &[u8],
    image_base: u32,
    code: &impl Fn(u32) -> Option<&'a [u8]>,
) -> Option<()> {
    let (dispatch, result, push, push_call) = if matches_pattern(body, DIRECT_DISPATCH) {
        (DIRECT_DISPATCH, DIRECT_RESULT, DIRECT_PUSH, 12)
    } else if matches_pattern(body, REORDERED_DISPATCH) {
        (REORDERED_DISPATCH, REORDERED_RESULT, REORDERED_PUSH, 13)
    } else {
        return None;
    };
    let decoder = call_target(rva, body, 29)?;
    if decoder != call_target(rva, body, 46)? {
        return None;
    }
    verify_operand_decoder(decoder, image_base, code)?;

    let table = read_word(body, dispatch.len() - 4)?.checked_sub(image_base)?;
    let result_rva = read_word(code(table)?, 4)?.checked_sub(image_base)?;
    // Status 1 goes to a block inside the same dispatcher.
    if result_rva < rva.checked_add(dispatch.len() as u32)? || result_rva >= table {
        return None;
    }
    let body = code(result_rva)?;
    if !matches_pattern(body, result) {
        return None;
    }
    let stack_push = code(call_target(result_rva, body, push_call)?)?;
    stack_push.starts_with(push).then_some(())
}

fn verify_operand_decoder<'a>(
    rva: u32,
    image_base: u32,
    code: &impl Fn(u32) -> Option<&'a [u8]>,
) -> Option<()> {
    let body = code(rva)?;
    let (calls, switches) = if matches_pattern(body, COMPACT_OPERAND) {
        ([[70, 233], [95, 256]], [(130, [134, 163, 192, 192]), (290, [294, 313, 332, 332])])
    } else if matches_pattern(body, SAVED_EBP_OPERAND) {
        ([[88, 265], [113, 288]], [(150, [154, 187, 220, 220]), (321, [325, 344, 363, 363])])
    } else if matches_pattern(body, DEBUG_ITERATOR_OPERAND) {
        ([[77, 289], [101, 311]], [(137, [141, 172, 203, 232]), (345, [349, 376, 397, 412])])
    } else {
        return None;
    };

    for [first, second] in calls {
        let target = call_target(rva, body, first)?;
        if target != call_target(rva, body, second)? {
            return None;
        }
        code(target)?;
    }
    for (operand, targets) in switches {
        let table = read_word(body, operand)?.checked_sub(image_base)?;
        let entries = code(table)?;
        for (index, target) in targets.into_iter().enumerate() {
            let target_rva = read_word(entries, index * 4)?.checked_sub(image_base)?;
            if target_rva != rva.checked_add(target)? {
                return None;
            }
        }
    }
    Some(())
}

fn call_target(rva: u32, body: &[u8], operand: usize) -> Option<u32> {
    relative_target(rva, operand, read_word(body, operand)?)
}

fn matches_pattern(body: &[u8], pattern: &[u8]) -> bool {
    body.get(..pattern.len()).is_some_and(|body| {
        body.iter().zip(pattern).all(|(&actual, &expected)| expected == b'?' || actual == expected)
    })
}

